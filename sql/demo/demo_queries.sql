-- Demo queries: what each layer produced. Run with `python -m skypoints.demo`, or paste into
-- a Snowsight worksheet with the pipeline database selected. Each "-- name:" starts a query.

-- name: 1. Bronze: every file loaded exactly once (META.FILE_LOAD_LOG)
SELECT FILE_NAME, STATUS, ROWS_LOADED, ERRORS_SEEN, LEFT(FILE_MD5, 8) AS MD5
FROM META.FILE_LOAD_LOG
ORDER BY BATCH_DATE, FEED;

-- name: 2. Silver members: why rows were rejected (MEMBER_REJECT)
SELECT r.VALUE::STRING AS REASON, COUNT(*) AS ROWS_REJECTED
FROM SILVER.MEMBER_REJECT, LATERAL FLATTEN(REJECT_REASONS) r
GROUP BY 1 ORDER BY 2 DESC;

-- name: 3. Silver members: kept but flagged (DQ_FLAGS in MEMBER_STG)
SELECT f.VALUE::STRING AS FLAG, COUNT(*) AS ROWS_KEPT
FROM SILVER.MEMBER_STG, LATERAL FLATTEN(DQ_FLAGS) f
GROUP BY 1 ORDER BY 2 DESC;

-- name: 4. Traceability: a repaired DOB, raw Bronze value next to the Silver value
SELECT s.MEMBER_ID, b.DOB AS RAW_DOB, s.DOB AS SILVER_DOB, s.AGE, s.SOURCE_FILE, s.SOURCE_FILE_ROW_NO
FROM SILVER.MEMBER_STG s
JOIN BRONZE.MEMBER_PROFILE_RAW b
    ON b.SOURCE_FILE = s.SOURCE_FILE AND b.SOURCE_FILE_ROW_NO = s.SOURCE_FILE_ROW_NO
WHERE ARRAY_CONTAINS('DOB_REPAIRED'::VARIANT, s.DQ_FLAGS)
ORDER BY s.MEMBER_ID
LIMIT 3;

-- name: 5. Latest record wins: members who moved country
SELECT MEMBER_ID, PREVIOUS_COUNTRY_ISO AS FROM_ISO, COUNTRY_ISO AS TO_ISO, TARGET_TABLE,
       COUNTRY_CHANGED_DATE
FROM SILVER.MEMBER_CURRENT
WHERE PREVIOUS_COUNTRY_ISO IS NOT NULL
ORDER BY COUNTRY_CHANGED_DATE, MEMBER_ID
LIMIT 5;

-- name: 6. Country split: each member in exactly one country table (DUPLICATES must be 0)
WITH all_tables AS (
    SELECT MEMBER_ID FROM SILVER.MEMBER_US UNION ALL
    SELECT MEMBER_ID FROM SILVER.MEMBER_IN UNION ALL
    SELECT MEMBER_ID FROM SILVER.MEMBER_PH UNION ALL
    SELECT MEMBER_ID FROM SILVER.MEMBER_CA UNION ALL
    SELECT MEMBER_ID FROM SILVER.MEMBER_AU UNION ALL
    SELECT MEMBER_ID FROM SILVER.MEMBER_UNMAPPED
)
SELECT (SELECT COUNT(*) FROM SILVER.MEMBER_CURRENT) AS CURRENT_MEMBERS,
       COUNT(*) AS COUNTRY_TABLE_ROWS,
       COUNT(*) - COUNT(DISTINCT MEMBER_ID) AS DUPLICATES
FROM all_tables;

-- name: 7. Silver redemptions: why transactions were rejected
SELECT r.VALUE::STRING AS REASON, COUNT(*) AS TXNS_REJECTED
FROM SILVER.REDEMPTION_REJECT, LATERAL FLATTEN(REJECT_REASONS) r
GROUP BY 1 ORDER BY 2 DESC;

-- name: 8. Orphans: redemptions whose member has not arrived (kept, not dropped)
SELECT TXN_ID, MEMBER_ID, PARTNER, MILES_REDEEMED, BATCH_DATE
FROM SILVER.V_REDEMPTION_ORPHAN
ORDER BY BATCH_DATE, TXN_ID;

-- name: 9. Gold SCD2: one member's history in DIM_MEMBER
SELECT MEMBER_ID, VERSION_NO, COUNTRY_ISO, TIER_CODE, IS_ACTIVE, VALID_FROM, VALID_TO, IS_CURRENT
FROM GOLD.DIM_MEMBER
WHERE MEMBER_ID = (SELECT MEMBER_ID FROM GOLD.DIM_MEMBER
                   GROUP BY 1 ORDER BY COUNT(*) DESC, 1 LIMIT 1)
ORDER BY VERSION_NO;

-- name: 10. Gold point-in-time join: the country a member was in when they redeemed
SELECT r.TXN_ID, r.MEMBER_ID, r.TXN_DATE, d.COUNTRY_ISO AS COUNTRY_AT_TXN,
       m.COUNTRY_ISO AS COUNTRY_NOW, r.MILES_REDEEMED
FROM SILVER.REDEMPTION_TXN r
JOIN GOLD.DIM_MEMBER d
    ON d.MEMBER_ID = r.MEMBER_ID AND r.TXN_DATE BETWEEN d.VALID_FROM AND d.VALID_TO
JOIN SILVER.MEMBER_CURRENT m ON m.MEMBER_ID = r.MEMBER_ID
WHERE NOT EQUAL_NULL(d.COUNTRY_ISO, m.COUNTRY_ISO)
ORDER BY r.TXN_DATE, r.TXN_ID
LIMIT 5;

-- name: 11. Gold MEMBER_360: lifecycle by country
SELECT COALESCE(COUNTRY_ISO, '??') AS COUNTRY, LIFECYCLE_STATUS, COUNT(*) AS MEMBERS,
       SUM(COMPLETED_MILES) AS COMPLETED_MILES, COUNT_IF(DORMANT_REDEEMER) AS DORMANT_REDEEMERS
FROM GOLD.MEMBER_360
GROUP BY 1, 2
ORDER BY 1, 2;

-- name: 12. Gold MEMBER_360: top redeemers
SELECT MEMBER_ID, MEMBER_NAME, COUNTRY_ISO, TIER_CODE, TXN_COUNT, COMPLETED_MILES,
       FAVOURITE_PARTNER, LIFECYCLE_STATUS
FROM GOLD.MEMBER_360
ORDER BY COMPLETED_MILES DESC, MEMBER_ID
LIMIT 5;
