-- Load one batch into REDEMPTION_TXN / REDEMPTION_REJECT, then re-check orphans.
-- Idempotent: the batch is replaced. Expects {{ silver }}.REDEMPTION_BATCH_TMP built from
-- redemption_validate.sql in the same session.

BEGIN;

DELETE FROM {{ silver }}.REDEMPTION_TXN    WHERE BATCH_DATE = '{{ batch_date }}'::DATE;
DELETE FROM {{ silver }}.REDEMPTION_REJECT WHERE BATCH_DATE = '{{ batch_date }}'::DATE;

INSERT INTO {{ silver }}.REDEMPTION_TXN (
    TXN_ID, MEMBER_ID, FEED_DATE, TXN_DATE, PARTNER, IS_INTERNAL_PARTNER, MILES_REDEEMED,
    STATUS, IS_COMPLETED, FEED_LAG_DAYS, ORPHAN_MEMBER, DQ_FLAGS, BATCH_DATE, SOURCE_FILE,
    SOURCE_FILE_ROW_NO, TXN_INDEX, LOAD_ID)
SELECT
    TXN_ID, MEMBER_ID, FEED_DATE, TXN_DATE, PARTNER, IS_INTERNAL_PARTNER, MILES_REDEEMED,
    STATUS, IS_COMPLETED, FEED_LAG_DAYS, ORPHAN_MEMBER, DQ_FLAGS, BATCH_DATE, SOURCE_FILE,
    SOURCE_FILE_ROW_NO, TXN_INDEX, LOAD_ID
FROM {{ silver }}.REDEMPTION_BATCH_TMP
WHERE ARRAY_SIZE(REJECT_REASONS) = 0;

INSERT INTO {{ silver }}.REDEMPTION_REJECT (
    BATCH_DATE, MEMBER_ID_RAW, TXN_ID_RAW, REJECT_REASONS, RAW_VALUE, SOURCE_FILE,
    SOURCE_FILE_ROW_NO, TXN_INDEX, LOAD_ID)
SELECT
    BATCH_DATE, MEMBER_ID_RAW, TXN_ID_RAW, REJECT_REASONS, RAW_VALUE, SOURCE_FILE,
    SOURCE_FILE_ROW_NO, TXN_INDEX, LOAD_ID
FROM {{ silver }}.REDEMPTION_BATCH_TMP
WHERE ARRAY_SIZE(REJECT_REASONS) > 0;

-- Late-arriving members: orphans from any earlier batch whose member now exists.
UPDATE {{ silver }}.REDEMPTION_TXN
SET ORPHAN_MEMBER = FALSE,
    ORPHAN_RESOLVED_BATCH = '{{ batch_date }}'::DATE
WHERE ORPHAN_MEMBER
  AND MEMBER_ID IN (SELECT MEMBER_ID FROM {{ silver }}.MEMBER_CURRENT);

COMMIT;
