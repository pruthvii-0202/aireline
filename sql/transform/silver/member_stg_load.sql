-- Load one batch into MEMBER_STG / MEMBER_REJECT. Idempotent: the batch is replaced, so
-- re-running gives the same result. Expects SILVER.MEMBER_BATCH_TMP built from
-- member_validate.sql in the same session.

BEGIN;

DELETE FROM {{ database }}.SILVER.MEMBER_STG    WHERE BATCH_DATE = '{{ batch_date }}'::DATE;
DELETE FROM {{ database }}.SILVER.MEMBER_REJECT WHERE BATCH_DATE = '{{ batch_date }}'::DATE;

INSERT INTO {{ database }}.SILVER.MEMBER_STG (
    BATCH_DATE, MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE,
    AGENT_NAME, STATE, COUNTRY_RAW, COUNTRY_ISO, DOB, IS_ACTIVE, AGE, DAYS_SINCE_LAST_FLIGHT,
    STALE_MEMBER, NEVER_FLOWN, DQ_FLAGS, RECORD_HASH, SOURCE_FILE, SOURCE_FILE_ROW_NO,
    LOAD_ID, LOAD_TS)
SELECT
    BATCH_DATE, MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE,
    AGENT_NAME, STATE, COUNTRY_RAW, COUNTRY_ISO, DOB, IS_ACTIVE, AGE, DAYS_SINCE_LAST_FLIGHT,
    STALE_MEMBER, NEVER_FLOWN, DQ_FLAGS, RECORD_HASH, SOURCE_FILE, SOURCE_FILE_ROW_NO,
    LOAD_ID, LOAD_TS
FROM {{ database }}.SILVER.MEMBER_BATCH_TMP
WHERE ARRAY_SIZE(REJECT_REASONS) = 0;

INSERT INTO {{ database }}.SILVER.MEMBER_REJECT (
    BATCH_DATE, MEMBER_ID_RAW, REJECT_REASONS, RAW_RECORD, SOURCE_FILE, SOURCE_FILE_ROW_NO, LOAD_ID)
SELECT
    BATCH_DATE, MEMBER_ID_RAW, REJECT_REASONS, RAW_RECORD, SOURCE_FILE, SOURCE_FILE_ROW_NO, LOAD_ID
FROM {{ database }}.SILVER.MEMBER_BATCH_TMP
WHERE ARRAY_SIZE(REJECT_REASONS) > 0;

COMMIT;
